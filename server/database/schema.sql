CREATE TABLE IF NOT EXISTS hr_records (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  record_type TEXT NOT NULL CHECK (record_type IN (
    'vacancy', 'candidate', 'application', 'interview', 'onboarding',
    'onboarding-checklist', 'training', 'training-assignment', 'support-case', 'task'
  )),
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 160),
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL,
  employee_id UUID REFERENCES app_users(id) ON DELETE SET NULL,
  assigned_to UUID REFERENCES app_users(id) ON DELETE SET NULL,
  related_record_id UUID REFERENCES hr_records(id) ON DELETE SET NULL,
  due_date DATE,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
  updated_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hr_records_type_created_idx
  ON hr_records (record_type, created_at DESC);
CREATE INDEX IF NOT EXISTS hr_records_employee_idx
  ON hr_records (employee_id, record_type);
CREATE INDEX IF NOT EXISTS hr_records_assignee_status_idx
  ON hr_records (assigned_to, status);
CREATE INDEX IF NOT EXISTS hr_records_related_idx
  ON hr_records (related_record_id);

CREATE TABLE IF NOT EXISTS hr_leave_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000),
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  reviewed_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS hr_leave_employee_created_idx
  ON hr_leave_requests (employee_id, created_at DESC);
CREATE INDEX IF NOT EXISTS hr_leave_status_created_idx
  ON hr_leave_requests (status, created_at DESC);

CREATE TABLE IF NOT EXISTS hr_attendance (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  work_date DATE NOT NULL DEFAULT CURRENT_DATE,
  check_in TIMESTAMPTZ,
  check_out TIMESTAMPTZ,
  note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (employee_id, work_date),
  CHECK (check_out IS NULL OR check_in IS NOT NULL),
  CHECK (check_out IS NULL OR check_out >= check_in)
);

CREATE INDEX IF NOT EXISTS hr_attendance_date_employee_idx
  ON hr_attendance (work_date DESC, employee_id);

CREATE TABLE IF NOT EXISTS hr_documents (
