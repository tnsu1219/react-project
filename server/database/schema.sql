CREATE TABLE IF NOT EXISTS app_users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  department TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS is_blocked BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_users DROP CONSTRAINT IF EXISTS app_users_role_check;
ALTER TABLE app_users ADD CONSTRAINT app_users_role_check CHECK (role IN ('user', 'customer', 'admin'));
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS full_name TEXT;

CREATE TABLE IF NOT EXISTS customer_profiles (
  customer_id UUID PRIMARY KEY REFERENCES app_users(id) ON DELETE CASCADE,
  phone TEXT NOT NULL DEFAULT '',
  area TEXT NOT NULL DEFAULT '',
  street TEXT NOT NULL DEFAULT '',
  main_road TEXT NOT NULL DEFAULT '',
  home_number TEXT NOT NULL DEFAULT '',
  delivery_notes TEXT NOT NULL DEFAULT '',
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180))
);

CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  sku TEXT UNIQUE,
  category TEXT NOT NULL DEFAULT 'General',
  description TEXT NOT NULL DEFAULT '',
  quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS customer_orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'placed' CHECK (status IN ('placed', 'accepted', 'preparing', 'out_for_delivery', 'delivered', 'cancelled')),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('telebirr', 'cbe', 'other_bank', 'cash_on_delivery')),
  payment_status TEXT NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'paid', 'failed')),
  payment_reference TEXT,
  delivery_address TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180))
);

CREATE INDEX IF NOT EXISTS customer_orders_customer_created_idx
  ON customer_orders (customer_id, created_at DESC);

CREATE TABLE IF NOT EXISTS customer_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id UUID NOT NULL REFERENCES customer_orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
  line_total NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0)
);

CREATE INDEX IF NOT EXISTS customer_order_items_order_idx
  ON customer_order_items (order_id);

CREATE TABLE IF NOT EXISTS company_payment_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL CHECK (provider IN ('telebirr', 'cbe', 'other_bank')),
  display_name TEXT NOT NULL,
  account_name TEXT NOT NULL,
  account_number TEXT NOT NULL,
  instructions TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE customer_orders
  ADD COLUMN IF NOT EXISTS payment_account_id BIGINT REFERENCES company_payment_accounts(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS customer_payment_submissions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id UUID NOT NULL REFERENCES customer_orders(id) ON DELETE CASCADE,
  customer_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  payment_account_id BIGINT REFERENCES company_payment_accounts(id) ON DELETE SET NULL,
  payment_account_display_name TEXT,
  payment_account_name TEXT,
  payment_account_number TEXT,
  provider TEXT NOT NULL CHECK (provider IN ('telebirr', 'cbe', 'other_bank')),
  transaction_reference TEXT NOT NULL,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed')),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS payment_account_display_name TEXT;
ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS payment_account_name TEXT;
ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS payment_account_number TEXT;
ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS receipt_data BYTEA;
ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS receipt_content_type TEXT;
ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS receipt_file_name TEXT;
ALTER TABLE customer_payment_submissions ADD COLUMN IF NOT EXISTS remarks TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS customer_payment_submissions_order_idx
  ON customer_payment_submissions (order_id, submitted_at DESC);

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description TEXT NOT NULL,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
  type TEXT NOT NULL CHECK (type IN ('Income', 'Expense')),
  category TEXT NOT NULL DEFAULT 'General',
  status TEXT NOT NULL DEFAULT 'Completed',
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS support_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_type TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  source_department TEXT NOT NULL,
  target_department TEXT NOT NULL DEFAULT 'IT',
  reported_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
  reporter_email TEXT,
  status TEXT NOT NULL DEFAULT 'Open',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS support_requests_reporter_created_idx
  ON support_requests (reported_by, created_at DESC);

CREATE INDEX IF NOT EXISTS support_requests_target_created_idx
  ON support_requests (target_department, created_at DESC);

CREATE TABLE IF NOT EXISTS support_request_replies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  support_request_id BIGINT NOT NULL REFERENCES support_requests(id) ON DELETE CASCADE,
  replied_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
  response_type TEXT NOT NULL CHECK (response_type IN ('available', 'busy', 'delayed', 'ready', 'need_info', 'custom')),
  message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS support_request_replies_request_created_idx
  ON support_request_replies (support_request_id, created_at DESC);

CREATE TABLE IF NOT EXISTS department_work_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  department TEXT NOT NULL CHECK (department IN ('IT', 'Sales', 'Finance', 'Mainstore', 'Attendance', 'Auditor', 'Logistics')),
  created_by UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  legacy_key TEXT,
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  details TEXT NOT NULL CHECK (char_length(details) BETWEEN 1 AND 1000),
  status TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (created_by, legacy_key)
);

CREATE INDEX IF NOT EXISTS department_work_items_department_created_idx
  ON department_work_items (department, created_at DESC);